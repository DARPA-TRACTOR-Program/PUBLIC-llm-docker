def indent(contents: str, indent_with: str = "    "):
    return "\n".join(indent_with + s for s in contents.split("\n"))


def extract_code(response: str) -> str | None:
    # strip any "```"/"```rust" code block delimiters as well as any leading/trailing whitespace
    if "```" not in response:
        return response.strip()
    block_start = response.index("```")
    start_idx = response.index("\n", block_start+3)
    end_idx = response.rindex("```")
    response = response[start_idx:end_idx].strip()

    if "```" in response:
        print(f"Unable to parse response: multiple code blocks detected. Raw response:\n" +
              indent(f"```\n{response}\n```"))
        return None

    return response


def get_input_files(src_root: Path) -> list[Path]:
    with TemporaryDirectory() as tmp:
        print("Build directory:", tmp)
        print("Generating compile commands...")
        args = ["cmake", "-DCMAKE_EXPORT_COMPILE_COMMANDS=1",
                src_root / "CMakeLists.txt"]
        subprocess.run(args, cwd=tmp, check=True)

        with open(Path(tmp) / "compile_commands.json", "rb") as f:
            compile_commands = json.load(f)

    return [src_root / cmd["file"] for cmd in compile_commands if "file" in cmd]


def strip_license(source: str) -> str:
    """Licenses comprise a lot of tokens. Strip them so we don't overwhelm the LLM"""
    return re.sub(r'(?m)^// Copyright (?:[^\n]*\n// )*[^\n]*SOFTWARE\.', "", source).strip()


def base_prompt_from_files(files: list[Path]) -> str:
    prompt = ""
    for file in files:
        with open(file, "r") as f:
            source = strip_license(f.read().strip())
        prompt += f"`{file.name}`:\n```\n{source}\n```\n\n"
    return prompt


def run_rustfmt(source: str) -> str:
    proc = subprocess.run(["rustfmt"], text=True,
                          input=source, stdout=subprocess.PIPE, check=True)
    return proc.stdout.strip()


def run_bindgen(src_root: Path, headers: list[Path]) -> str:
    """Generates a C-compatible template using bindgen, as cleanly and minimally as possible"""

    with TemporaryDirectory() as tmp:
        header_source = ""
        for h in headers:
            header_source += f'#include "{h}"\n'
        with open(Path(tmp) / "wrapper.h", "w") as f:
            f.write(header_source)
        proc = subprocess.run(["bindgen", "--disable-header-comment", "--no-layout-tests", "--no-doc-comments",
                              "wrapper.h", "--", "-I", f"{src_root}"], cwd=tmp, text=True, stdout=subprocess.PIPE, check=True)
        source = proc.stdout.strip()

    source = "use std::os::raw::*;\n" + source.replace("::std::os::raw::", "")
    source = re.sub(
        r'(?m)^unsafe extern "C" \{\s*pub fn ([^;}]*);\s*\}', r'pub unsafe extern "C" fn \1 { todo!() }', source)
    source = run_rustfmt(source)
    source = source.replace("todo!()", "/* IMPLEMENT ME */")
    return source


def prompt_for_first_attempt(src_root: Path, input_files: list[Path], c_compatible_lib: bool) -> str:
    prompt = base_prompt_from_files(input_files)

    if c_compatible_lib:
        # TODO: try to get headers via CMake `INTERFACE_INCLUDE_DIRECTORIES` instead of hardcoded glob `include/*.h`
        headers = list(src_root.glob("include/*.h"))
        if not headers:
            raise RuntimeError(
                "Unable to find any headers in the project 'include' directory. Headers are required when using `--c-compatible-lib`.")

        interface = run_bindgen(src_root, headers)
        prompt += f"Convert the above library from C to Rust. Follow this FFI-compatible template:\n\n```\n{interface}\n```\n\n"
    else:
        prompt += "Convert the above program from C to Rust. "

    prompt += "Respond directly with a single file of Rust code and no other information. Replace `printf` and other functions with their Rust equivalents."
    return prompt


def main_file_path(out_dir: Path, c_compatible_lib: bool):
    if c_compatible_lib:
        return out_dir / "src" / "lib.rs"
    else:
        return out_dir / "src" / "main.rs"


def write_response(out_dir: Path, response: str, c_compatible_lib: bool, target_name: str):
    os.makedirs(out_dir, exist_ok=True)
    for child in out_dir.iterdir():
        if child.is_dir():
            shutil.rmtree(child)
        elif all(keep_file not in str(child) for keep_file in ["stdout.log", "stderr.log"]):
            # Do not delete stdout.lg + stderr.log (so we can debug naive.py bugs)
            child.unlink()

    os.makedirs(out_dir / "src", exist_ok=True)
    with open(main_file_path(out_dir, c_compatible_lib), "w") as f:
        f.write(response)

    with open(out_dir / "Cargo.toml", "w") as f:
        cargo_toml = \
            f"""\
[package]
name = "{target_name}"
version = "0.1.0"
edition = "2021"
publish = false

[dependencies]
rand = "0.8"
"""

        if c_compatible_lib:
            cargo_toml += \
                """\

[lib]
crate-type = ["cdylib"]
"""
        f.write(cargo_toml)


def collect_errors(out_dir: Path) -> str | None:
    proc = subprocess.run(["cargo", "check"], cwd=out_dir,
                          text=True, stderr=subprocess.PIPE)
    if proc.returncode == 0:
        return None

    # find all blocks of consecutive non-empty lines, where the block begins with "error"
    # (strip out warnings and other unimportant messages; we want to minimize the length of the prompt)
    error_str = ""
    inside_error = False
    for line in proc.stderr.splitlines():
        line = line.strip("\r\n")
        if line == "" or line.startswith("error: could not compile"):
            inside_error = False
        elif line.startswith("error"):
            inside_error = True
            if len(error_str) != 0:
                error_str += "\n"

        if inside_error:
            error_str += f"{line}\n"

    return error_str if len(error_str) > 0 else proc.stderr


def try_auto_fix(out_dir: Path):
    subprocess.run(["cargo", "fix", "--allow-no-vcs"],
                   cwd=out_dir, stderr=subprocess.DEVNULL)
    subprocess.run(["cargo", "clippy", "--fix", "--allow-no-vcs"],
                   cwd=out_dir, stderr=subprocess.DEVNULL)


def try_llm_fix(out_dir: Path, error_str: str, ask_llm: Callable[[str], str], c_compatible_lib: bool):
    main_file = main_file_path(out_dir, c_compatible_lib)
    prompt = base_prompt_from_files([main_file])
    prompt += f"Fix these errors:\n```\n{error_str}\n```\nRespond directly with a file containing the full contents of the fixed code."
    print("Waiting... ", end="", flush=True)

    response = ask_llm(prompt)
    response = extract_code(response)
    if response is None:
        return
    print("\nRESPONSE:\n" + indent(response) + "\n")

    with open(main_file, "w") as f:
        f.write(response)


class ParsedArgs(Protocol):
    try_convert: int  # max number of conversion attempts
    try_fix: int  # when a conversion attempt fails, send more prompts to try to fix it)
    openai: Optional[str]  # e.g., gpt-5
    ollama: Optional[str]
    c_compatible_lib: Optional[bool]
    src_root: Path
    out_dir: Path


def do_translation(args: ParsedArgs):
    # fmt: off
    ask_llm: Callable[[str], str]
    if args.openai is not None:
        ask_llm = lambda p: ask_llm_openai(p, model=cast(str, args.openai))
    elif args.ollama is not None:
        ask_llm = lambda p: ask_llm_ollama(p, model=cast(str, args.ollama))
    else:
        ask_llm = lambda p: ask_llm_ollama(p)
    # fmt: on

    input_files = get_input_files(args.src_root)
    prompt = prompt_for_first_attempt(
        args.src_root, input_files, args.c_compatible_lib)

    target_name = get_target(args.src_root)

    ok = False
    for conversion_attempt in range(1, args.try_convert+1):
        print("\nPROMPT:")
        print(prompt)
        print()
        print(f"Conversion attempt #{conversion_attempt}")
        print("Waiting... ", end="", flush=True)

        response = ask_llm(prompt).strip()
        response = extract_code(response)
        if response is None:
            continue

        print("\nRESPONSE:\n" + indent(response) + "\n")

        write_response(args.out_dir, response, args.c_compatible_lib, target_name)

        # Use "cargo check" to verify output is compilable Rust
        fix_attempt = 1
        while True:
            try_auto_fix(args.out_dir)
            error_str = collect_errors(args.out_dir)
            if error_str is None:
                # got a good result => return early
                ok = True
                break
            if fix_attempt > args.try_fix:
                break
            print(f"Fix attempt #{fix_attempt} with errors:\n{error_str}\n")
            try_llm_fix(args.out_dir, error_str,
                        ask_llm, args.c_compatible_lib)
            fix_attempt += 1
        if ok:
            break

        print("Error: exceeded maximum fix attempts without a successful translation.")

    if ok:
        print("Done.")
        print(f"(Try `cd {args.out_dir} && cargo run`)")
        return

    print("Error: exceeded maximum conversion attempts without a successful translation.")
    sys.exit(1)


