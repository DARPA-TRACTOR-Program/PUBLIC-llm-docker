def get_target(rootdir: str) -> str:
    cmake_cmd = ["/app/cmake_commands.sh", rootdir]
    # need to run cmake here....
    subprocess.run(cmake_cmd, cwd=rootdir, check=True)

    # Parse a CMake file API response for codemodel-v2
    # to extract the name of the library or executable
    # generated by the build process,
    # and to determine whether it is an executable.

    # The response is generated when the empty file
    # ".cmake/api/v1/query/codemodel-v2"
    # exists in the working directory when cmake is invoked.

    # Takes one arguments:
    # 1. A path to the directory cmake was invoked from (containing .cmake)
    cmake_reply_root = Path(rootdir) / "build" / ".cmake" / "api" / "v1" / "reply"

    # load index of response
    index_path = tuple(cmake_reply_root.glob("index-*.json"))[0]
    with open(index_path, "r") as f:
        index = json.load(f)

    # load codemodel reply
    codemodel_filename = index["reply"]["codemodel-v2"]["jsonFile"]
    codemodel_path = cmake_reply_root / codemodel_filename
    with open(codemodel_path, "r") as f:
        codemodel = json.load(f)

    # assume one translated build configuration and one target (for now)
    target_filename = codemodel["configurations"][0]["targets"][0]["jsonFile"]
    target_path = cmake_reply_root / target_filename
    with open(target_path, "r") as f:
        target = json.load(f)
    print(target["name"])
    return target["name"]



def ask_llm_ollama(prompt: str, model: str = "llama3.2") -> str:
    client = ollama.Client()
    response = client.chat(
        model=model,
        messages=[{"role": "user", "content": prompt}],
        options=ollama.Options(temperature=0)
    )

    res = response.message.content
    assert res is not None  # satisfy type checker
    return res


